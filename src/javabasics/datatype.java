public class datatype {
    public static void main(String[] args) {
        int myNum = 5;               // Integer (whole number)
        float myFloatNum = 5.99f;   // Floating point number
        char myLetter = 'D';        // Character
        boolean myBool = true;      // Boolean
        String myText = "Hello";    // String

        System.out.println("Integer: " + myNum);
        System.out.println("Float: " + myFloatNum);
        System.out.println("Character: " + myLetter);
        System.out.println("Boolean: " + myBool);
        System.out.println("String: " + myText);
        // non primitive stores references of objects not the actuall value directly
        //java has 8 primitive data types: byte, short, int, long, float, double, boolean, and char.
        // java has 4 non-primitive data types: String, Arrays, Classes, and Interfaces.
    }
}
